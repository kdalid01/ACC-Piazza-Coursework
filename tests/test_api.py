
from fastapi.testclient import TestClient


def test_starts_empty(client):
    response = client.get("/posts")

    assert response.status_code == 200
    assert response.json() == []



def test_create_and_retrieve(client):
    # Data sent to the API to create a post.
    post_data = {
        "title": "Cloud computing",
        "body": "What are the advantages of containers?",
        "expires_at": "2027-06-01T12:00:00Z"
    }

    # Create a new post.
    created = client.post("/posts", json=post_data)

    # Check that the post was created successfully.
    assert created.status_code == 201

    # Get the ID generated by the database.
    post_id = created.json()["id"]

    # Retrieve the post using its ID.
    retrieved = client.get(f"/posts/{post_id}")

    # Check that the request succeeded.
    assert retrieved.status_code == 200

    # Check that the retrieved data matches the created post.
    assert retrieved.json() == created.json()


def test_missing_post(client):
    response = client.get("/posts/9999")

    assert response.status_code == 404
    assert response.json() == {"detail": "Post not found"}



def test_invalid_post(client):
    post_data = {
        "title": "",
        "body": "This post has an empty title.",
        "expires_at": "2027-06-01T12:00:00Z"
    }

    response = client.post("/posts", json=post_data)

    assert response.status_code == 422



def test_data_survives_new_application(app_factory):
    post_data = {
        "title": "Cloud computing",
        "body": "What are the advantages of containers?",
        "expires_at": "2027-06-01T12:00:00Z"
    }

    # Create a post using the first application instance.
    with TestClient(app_factory()) as first:
        created = first.post("/posts", json=post_data)

        assert created.status_code == 201
        body = created.json()

    # Create a second application instance using the same database.
    with TestClient(app_factory()) as restarted:
        response = restarted.get(f"/posts/{body['id']}")

        assert response.status_code == 200
        assert response.json() == body

